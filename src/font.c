static void bake_glyph(int slot, const uint8_t rows[8])
{
    int cell_x = (slot & 15) * 8;
    int cell_y = (slot >> 4) * 8;
    for (int ry = 0; ry < 8; ry++) {
        uint8_t bits = rows[ry];
        for (int rx = 0; rx < 8; rx++) {
            /* Bit 5 is leftmost pixel (cols 0..5), cols 6..7 transparent spacing */
            bool on = (rx < 6) && ((bits & (0x20 >> rx)) != 0);
            s_font_atlas[(cell_y + ry) * 128 + (cell_x + rx)] =
                on ? 0xFFFFFFFFu : 0x00FFFFFFu;
        }
    }
}

void font_init(void)
{
    memset(s_font_atlas, 0, sizeof(s_font_atlas));
    for (int i = 0; i < 96; i++) {
        bake_glyph(32 + i, s_ascii_glyphs[i]);
    }
    for (int i = 0; i < 16; i++) {
        bake_glyph(128 + i, s_ext_glyphs[i]);
    }
    sceKernelDcacheWritebackAll();
}

static uint32_t utf8_next(const char **p)
{
    const unsigned char *s = (const unsigned char *)(*p);
    if (*s == 0) return 0;

    if (*s < 0x80) {
        *p += 1;
        return *s;
    }
    if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        uint32_t cp = ((uint32_t)(s[0] & 0x1F) << 6) | (uint32_t)(s[1] & 0x3F);
        *p += 2;
        return cp;
    }
    if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        uint32_t cp = ((uint32_t)(s[0] & 0x0F) << 12) |
                      ((uint32_t)(s[1] & 0x3F) << 6)  |
                      (uint32_t)(s[2] & 0x3F);
        *p += 3;
        return cp;
    }
    if ((s[0] & 0xF8) == 0xF0 && (s[1] & 0xC0) == 0x80 &&
        (s[2] & 0xC0) == 0x80 && (s[3] & 0xC0) == 0x80) {
        uint32_t cp = ((uint32_t)(s[0] & 0x07) << 18) |
                      ((uint32_t)(s[1] & 0x3F) << 12) |
                      ((uint32_t)(s[2] & 0x3F) << 6)  |
                      (uint32_t)(s[3] & 0x3F);
        *p += 4;
        return cp;
    }
    /* Fallback for raw Latin-1 / CP1254 byte */
    *p += 1;
    return *s;
}

static int map_codepoint_to_slot(uint32_t cp)
{
    if (cp >= 32 && cp <= 126) return (int)cp;

    switch (cp) {
        case 0x00C7: return EXT_C_CEDILLA; /* Ç */
        case 0x00E7: return EXT_c_CEDILLA; /* ç */
        case 0x011E: return EXT_G_BREVE;   /* Ğ */
        case 0x011F: return EXT_g_BREVE;   /* ğ */
        case 0x0130: return EXT_I_DOT;     /* İ */
        case 0x0131: return EXT_i_DOTLESS; /* ı */
        case 0x00D6: return EXT_O_DIA;     /* Ö */
        case 0x00F6: return EXT_o_DIA;     /* ö */
        case 0x015E: return EXT_S_CEDILLA; /* Ş */
        case 0x015F: return EXT_s_CEDILLA; /* ş */
        case 0x00DC: return EXT_U_DIA;     /* Ü */
        case 0x00FC: return EXT_u_DIA;     /* ü */
        case 0x00C9: case 0x00E9: case 0x00C8: case 0x00E8: case 0x00EA:
            return EXT_E_ACUTE;
        case 0x00C4: case 0x00E4: case 0x00C1: case 0x00E1: case 0x00C0: case 0x00E0: case 0x00C2: case 0x00E2:
            return EXT_A_DIA;
        case 0x00D1: case 0x00F1:
            return EXT_N_TILDE;
        case 0x266A: case 0x266B:
            return EXT_NOTE_ICON;
        case 0x2013: case 0x2014:
            return '-';
        case 0x2018: case 0x2019:
            return '\'';
        case 0x201C: case 0x201D:
            return '"';
        case 0x2022: case 0x00B7:
            return '*';
        default:
            return '?';
    }
}

float font_measure_utf8(const char *utf8, float scale)
{
    if (!utf8) return 0.0f;
    int chars = 0;
    const char *p = utf8;
    while (*p) {
        utf8_next(&p);
        chars++;
    }
    return (float)chars * 6.0f * scale;
}

void font_draw_utf8(float x, float y, const char *utf8, float scale, uint32_t color)
{
    if (!utf8 || !*utf8) return;

    /* Count glyphs first */
    int count = 0;
    const char *scan = utf8;
    while (*scan) {
        utf8_next(&scan);
        count++;
    }
    if (count <= 0) return;
    if (count > 256) count = 256;

    sceGuEnable(GU_TEXTURE_2D);
    sceGuTexMode(GU_PSM_8888, 0, 0, 0);
    sceGuTexImage(0, 128, 128, 128, s_font_atlas);
    sceGuTexFunc(GU_TFX_MODULATE, GU_TCC_RGBA);
    sceGuTexFilter(GU_NEAREST, GU_NEAREST);

    FontTexVertex *verts = (FontTexVertex *)sceGuGetMemory(count * 2 * sizeof(FontTexVertex));
    if (!verts) {
        sceGuDisable(GU_TEXTURE_2D);
        return;
    }

    float cx = x;
    float gw = 6.0f * scale;
    float gh = 8.0f * scale;

    const char *p = utf8;
    int vi = 0;
    for (int i = 0; i < count && *p; i++) {
        uint32_t cp = utf8_next(&p);
        int slot = map_codepoint_to_slot(cp);
        float u0 = (float)((slot & 15) * 8);
        float v0 = (float)((slot >> 4) * 8);

        verts[vi].u = u0;        verts[vi].v = v0;
        verts[vi].color = color;
        verts[vi].x = cx;        verts[vi].y = y;        verts[vi].z = 0.0f;
        vi++;

        verts[vi].u = u0 + 6.0f; verts[vi].v = v0 + 8.0f;
        verts[vi].color = color;
        verts[vi].x = cx + gw;   verts[vi].y = y + gh;   verts[vi].z = 0.0f;
        vi++;

        cx += gw;
    }

    sceGuDrawArray(GU_SPRITES,
                   GU_TEXTURE_32BITF | GU_COLOR_8888 | GU_VERTEX_32BITF | GU_TRANSFORM_2D,
                   vi, NULL, verts);

    sceGuDisable(GU_TEXTURE_2D);
}

void font_draw_utf8_ellipsis(float x, float y, float max_w,
                             const char *utf8, float scale, uint32_t color)
{
    if (!utf8 || max_w <= 0.0f) return;
    float full_w = font_measure_utf8(utf8, scale);
    if (full_w <= max_w) {
        font_draw_utf8(x, y, utf8, scale, color);
        return;
    }

    float char_w = 6.0f * scale;
    int max_chars = (int)(max_w / char_w);
    if (max_chars <= 3) return;

    char buf[256];
    int keep = max_chars - 2;
    const char *p = utf8;
    for (int i = 0; i < keep && *p; i++) {
        utf8_next(&p);
    }
    size_t byte_len = (size_t)(p - utf8);
    if (byte_len > sizeof(buf) - 4) byte_len = sizeof(buf) - 4;
    memcpy(buf, utf8, byte_len);
    buf[byte_len]     = '.';
    buf[byte_len + 1] = '.';
    buf[byte_len + 2] = '\0';

    font_draw_utf8(x, y, buf, scale, color);
}

/* 7-Segment bitmask:
 *   --0--
 *  |     |
 *  5     1
 *  |     |
 *   --6--
 *  |     |
 *  4     2
 *  |     |
 *   --3--
 */
static uint8_t seg_mask_for_char(char c)
{
    switch (c) {
        case '0': return 0x3F;
        case '1': return 0x06;
        case '2': return 0x5B;
        case '3': return 0x4F;
        case '4': return 0x66;
        case '5': return 0x6D;
        case '6': return 0x7D;
        case '7': return 0x07;
        case '8': return 0x7F;
        case '9': return 0x6F;
        case '-': return 0x40;
        default:  return 0x00;
    }
}

static void draw_one_7seg(float x, float y, float w, float h, float t,
                          uint8_t lit_mask, uint32_t lit_col, uint32_t ghost_col)
{
    float half_h = h * 0.5f;
    float gap = 1.0f;

    /* Segment 0: top horizontal */
    gfx_fill_rect(x + t + gap, y, w - 2.0f * (t + gap), t,
                  (lit_mask & 0x01) ? lit_col : ghost_col);
    /* Segment 1: top-right vertical */
    gfx_fill_rect(x + w - t, y + t + gap, t, half_h - 1.5f * t - gap,
                  (lit_mask & 0x02) ? lit_col : ghost_col);
    /* Segment 2: bottom-right vertical */
    gfx_fill_rect(x + w - t, y + half_h + 0.5f * t + gap, t, half_h - 1.5f * t - gap,
                  (lit_mask & 0x04) ? lit_col : ghost_col);
    /* Segment 3: bottom horizontal */
    gfx_fill_rect(x + t + gap, y + h - t, w - 2.0f * (t + gap), t,
                  (lit_mask & 0x08) ? lit_col : ghost_col);
    /* Segment 4: bottom-left vertical */
    gfx_fill_rect(x, y + half_h + 0.5f * t + gap, t, half_h - 1.5f * t - gap,
                  (lit_mask & 0x10) ? lit_col : ghost_col);
    /* Segment 5: top-left vertical */
    gfx_fill_rect(x, y + t + gap, t, half_h - 1.5f * t - gap,
                  (lit_mask & 0x20) ? lit_col : ghost_col);
    /* Segment 6: middle horizontal */
    gfx_fill_rect(x + t + gap, y + half_h - t * 0.5f, w - 2.0f * (t + gap), t,
                  (lit_mask & 0x40) ? lit_col : ghost_col);
}

float font_draw_7seg(float x, float y, float digit_w, float digit_h, float thick,
                     const char *text, uint32_t lit_col, uint32_t ghost_col)
{
    if (!text) return x;
    float cx = x;
    float spacing = digit_w * 0.25f + 1.5f;

    for (const char *p = text; *p; p++) {
        if (*p == ':') {
            float dot = thick + 0.5f;
            gfx_fill_rect(cx + 1.0f, y + digit_h * 0.28f, dot, dot, lit_col);
            gfx_fill_rect(cx + 1.0f, y + digit_h * 0.66f, dot, dot, lit_col);
            cx += dot + spacing + 1.0f;
        } else if (*p == ' ') {
            draw_one_7seg(cx, y, digit_w, digit_h, thick, 0x00, lit_col, ghost_col);
            cx += digit_w + spacing;
        } else {
            uint8_t mask = seg_mask_for_char(*p);
            draw_one_7seg(cx, y, digit_w, digit_h, thick, mask, lit_col, ghost_col);
            cx += digit_w + spacing;
        }
    }
    return cx;
}
